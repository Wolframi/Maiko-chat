import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readFile, mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const site = new URL("../", import.meta.url);
const crate = new URL("native/particle-graph/", site);
const metadata = new URL("artifact.json", crate);
const sourceHash = createHash("sha256");
for (const name of ["Cargo.toml", "Cargo.lock", "src/lib.rs"]) {
  sourceHash.update(name + "\0").update((await readFile(new URL(name, crate), "utf8")).replace(/\r\n/g, "\n"));
}
const sourceSha256 = sourceHash.digest("hex");
const digest = bytes => createHash("sha256").update(bytes).digest("hex");
const declaration = asset => `// Generated by scripts/prepare-particle-graph.mjs --build.\nexport const MAIKO_PARTICLE_WASM_URL = ${JSON.stringify(asset)};\n`;
const assetModule = new URL("src/lib/maikoParticleWasmAsset.ts", site);

if (process.argv.includes("--build")) {
  const target = new URL("../../output/particle-graph/target/", import.meta.url);
  execFileSync("cargo", ["build", "--manifest-path", fileURLToPath(new URL("Cargo.toml", crate)), "--locked",
    "--release", "--target", "wasm32-unknown-unknown", "--target-dir", fileURLToPath(target)],
  { stdio: "inherit", windowsHide: true });
  const bytes = await readFile(new URL("wasm32-unknown-unknown/release/maiko_particle_graph.wasm", target));
  const wasmSha256 = digest(bytes);
  const asset = `/wasm/maiko-particle-graph-${wasmSha256.slice(0, 16)}.wasm`;
  await mkdir(new URL("public/wasm/", site), { recursive: true });
  await writeFile(new URL(`public${asset}`, site), bytes);
  await writeFile(metadata, JSON.stringify({ asset, wasmSha256, sourceSha256 }, null, 2) + "\n");
  await writeFile(assetModule, declaration(asset));
}

// Ordinary builds verify the checked-in artifact; deployment machines do not need Rust.
try {
  const artifact = JSON.parse(await readFile(metadata, "utf8"));
  if (!/^\/wasm\/maiko-particle-graph-[a-f0-9]{16}\.wasm$/.test(artifact.asset)) throw new Error("Invalid WASM asset path");
  const bytes = await readFile(new URL(`public${artifact.asset}`, site));
  if (artifact.sourceSha256 !== sourceSha256 || digest(bytes) !== artifact.wasmSha256 ||
      !artifact.asset.includes(artifact.wasmSha256.slice(0, 16)) ||
      (await readFile(assetModule, "utf8")).replace(/\r\n/g, "\n") !== declaration(artifact.asset)) {
    throw new Error("Particle graph sources and WASM artifact differ");
  }
  console.log(`Particle graph WASM verified (${bytes.length} bytes).`);
} catch (error) {
  throw new Error("Rebuild the particle graph with npm run particles:build (Rust + wasm32-unknown-unknown required).", { cause: error });
}

execFileSync(process.execPath, ["--import", "tsx", fileURLToPath(new URL("scripts/prepare-particle-data.mts", site))],
  { cwd: fileURLToPath(site), stdio: "inherit", windowsHide: true });
